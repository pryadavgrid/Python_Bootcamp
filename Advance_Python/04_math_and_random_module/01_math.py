import math

my_value = 4.25
print(math.ceil(my_value)) # return Up Value
print(math.floor(my_value)) # return Down Value
print(round(my_value)) # roundOff value
print(math.pi) # return pi vslue

print(math.sqrt(16))  # squre root of number (n)^1/2
print(math.pow(2, 3))  # power of number : 2^3 -> 2 * 2* 2 
print(math.factorial(5))  # factorial of number : 5 * 4 * 3 * 2 * 1 = 120
print(math.gcd(12, 18))  # greatest common divisor of 12 and 18
print(math.sin(math.pi/2))  # Trigonometric functions (x in radians).
print(math.log(100, 10))  # Returns logarithm of x






